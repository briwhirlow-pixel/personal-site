/* Lean 185 service worker: keeps the app opening offline. API calls are never cached here. */
const CACHE = "lean185-shell-v1";
const SHELL = ["/lift", "/lift/index.html", "/lift/manifest.webmanifest", "/lift/icon-180.png", "/lift/icon-192.png", "/lift/icon-512.png"];
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", (e) => {
  const r = e.request, u = new URL(r.url);
  if (r.method !== "GET" || u.origin !== location.origin) return;
  if (!(u.pathname === "/lift" || u.pathname.startsWith("/lift/"))) return;
  e.respondWith(
    fetch(r).then((res) => {
      if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(r, copy)); }
      return res;
    }).catch(() => caches.match(r).then((m) => m || caches.match("/lift")))
  );
});
